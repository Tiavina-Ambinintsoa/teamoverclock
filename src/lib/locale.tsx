interface LocaleContextValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string) => string
  /** Texte bilingue en ligne : tx("Services", "Services") renvoie la version de la langue active. */
  tx: (fr: string, en: string) => string
  /** Balise BCP 47 pour Intl (dates, nombres) et la voix. */
  tag: string
}

const LocaleContext = createContext<LocaleContextValue | null>(null)

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const stored = safeStorage.get(LOCALE_KEY)
    return stored && isLocale(stored) ? stored : "fr"
  })

  const option = LOCALE_OPTIONS.find((entry) => entry.value === locale)
  const tag = option?.tag ?? "fr-FR"

  const setLocale = useCallback((next: Locale) => {
    safeStorage.set(LOCALE_KEY, next)
    setLocaleState(next)
    document.documentElement.lang = LOCALE_OPTIONS.find((entry) => entry.value === next)?.htmlTag ?? "fr-FR"
  }, [])

  useEffect(() => {
    document.documentElement.lang = option?.htmlTag ?? "fr-FR"
  }, [option?.htmlTag])

  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      setLocale,
      t(key) {
        const translated = messages[locale]?.[key]
        if (translated) return translated
        const english = messages.en?.[key] ?? key
        if (locale === "fr") return messages.fr?.[key] ?? english
        if (locale === "en") return english
        return translatePhrase(locale, english)
      },
      tx(fr, en) {
        if (locale === "fr") return fr
        if (locale === "en") return en
        return translatePhrase(locale, en)
      },
      tag,
    }),
    [locale, setLocale, tag],
  )

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  const context = useContext(LocaleContext)
  if (!context) throw new Error("useLocale doit être utilisé dans <LocaleProvider>")
  return context
}
